meta = meta[meta._file.str.startswith("bdshs")] if len(meta) else meta
if len(meta):
    for att in ("zwnj", "cgj", "vs16", "lrm"):
        d = meta[meta.attack == att]
        if len(d):
            nums[f"ins{att}"] = f"{d.mean_inserted.iloc[0]:.1f}"

        r = ben[(ben.dataset == "bdshs") & (ben.model == "banglat5") & (ben.seed == w.seed) & (ben.attack == "zwnj")]
        if len(r):
            nums["tfiveweakbenclean"], nums["tfiveweakbenatt"] = pct(r.benign_fpr_clean.iloc[0]), pct(r.benign_fpr_attacked.iloc[0])
        e = ev[(ev.dataset == "bdshs") & (ev.model == "banglat5") & (ev.seed == w.seed) & (ev.attack == "zwnj") & (ev.defense == "none")]
        if len(e):
            nums["tfiveweakev"] = pct(e.evasion.iloc[0])

    for lab, keys in (("340 real comments with ZW", ["wild zero-width (benign)"]),
                      ("all clean test comments", ["clean test (benign)"]),
                      ("invisible attacks (worst of 4)", [f"attack {a} (hate targets)" for a in ("zwnj", "cgj", "vs16", "lrm")]),
                      ("visible (unverified) attack", ["attack zwnj_ungated (hate targets)"])):
        r = f[f.set.isin(keys)]
        if not len(r):
            continue
        un = lambda c: pct(r[c].max()) if c in r and r[c].notna().any() else "--"
        rows.append([lab, pct(r.flag_rule.max()), pct(r.flag_decision.max()), un("unmitigated_rule"), un("unmitigated_decision")])
    table("tab_pipeline.tex", "tab:pipeline",
          "Review burden on XLM-R after the generalized defense (\\%). Unmitigated: evaded and never flagged.",
          ["Set", "Flag: rule", "decision", "Unmit.: rule", "decision"], rows)
    w = f[f.set == "wild zero-width (benign)"]
    t = f[f.set == "clean test (benign)"]
    if len(w):
        nums["flagwilddecision"] = pct(w.flag_decision.iloc[0])
    if len(t):
        nums["flagcleandecision"] = pct(t.flag_decision.iloc[0])
    att = f[f.set.str.startswith("attack")]

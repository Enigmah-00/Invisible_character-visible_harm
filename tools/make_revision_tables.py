    blp_seeds = sorted(ev_plain[ev_plain.dataset == "blp25"].seed.unique())
    blp_note = ("BLP-2025: seed 42." if len(blp_seeds) < 2 else "BLP-2025: mean$\\pm$sd over seeds " +
                ("42--44." if list(blp_seeds) == [42, 43, 44] else ", ".join(map(str, blp_seeds)) + "."))
    table("tab_crossmodel.tex", "tab:crossmodel",
          "Evasion (\\%) of the comments each model caught. BD-SHS: mean$\\pm$sd over seeds 42--44 for ZWNJ and "
          "CGJ, seed 42 otherwise; `Ours': worst case after the generalized defense. " + blp_note,
          ["Model", "Tokenizer", "Acc.", "ZWNJ", "CGJ", "VS16", "LRM", "Ours", "BLP acc.", "BLP ZWNJ", "BLP CGJ"],
          rows, star=True, align="llrrrrrrrrr")


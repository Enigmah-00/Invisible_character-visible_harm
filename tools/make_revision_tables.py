def load(suffix, per_run=False):
    fs = sorted(glob.glob(os.path.join(SRC, "**", f"*{suffix}"), recursive=True))
    fs = [f for f in fs if not os.path.basename(f).startswith(("rev1", "._")) and "__MACOSX" not in f]
    if per_run:   # classifier runs are <dataset>_<model>_s<seed>_<table>.csv (not llm_evasion.csv)
        fs = [f for f in fs if re.search(r"_s\d+" + re.escape(suffix) + "$", os.path.basename(f))]
    if not fs:
        return pd.DataFrame()
    return pd.concat([pd.read_csv(f).assign(_file=os.path.basename(f)) for f in fs],
                     ignore_index=True).drop_duplicates()


def wilson(k, n, z=1.96):
    if n == 0:
        return 0.0, 0.0
    p = k / n
    d = 1 + z * z / n
    c = (p + z * z / (2 * n)) / d
    h = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / d
    return max(0.0, c - h), min(1.0, c + h)


def pct(x):
    return f"{100 * x:.1f}"


def msd(xs):
    xs = [x for x in xs if x == x]
    if not xs:
        return "--"
    if len(xs) == 1:
        return pct(xs[0])
    m = sum(xs) / len(xs)
    sd = (sum((x - m) ** 2 for x in xs) / (len(xs) - 1)) ** 0.5
    return f"{100 * m:.1f}$\\pm${100 * sd:.1f}"


def table(path, label, caption, header, rows, star=False, align=None):
    env = "table*" if star else "table"
    width = "\\textwidth" if star else "\\columnwidth"
    align = align or "l" + "r" * (len(header) - 1)
    body = "\n".join(" & ".join(r) + " \\\\" for r in rows)
    open(os.path.join(DST, path), "w").write(
        f"% generated by tools/make_revision_tables.py -- do not edit\n"
        f"\\begin{{{env}}}[t]\n\\centering\n\\caption{{{caption}}}\n\\label{{{label}}}\n\\footnotesize\n"
        f"\\begin{{adjustbox}}{{max width={width}}}\n\\begin{{tabular}}{{{align}}}\n\\hline\n"
        f"{' & '.join(header)} \\\\\n\\hline\n{body}\n\\hline\n\\end{{tabular}}\n\\end{{adjustbox}}\n\\end{{{env}}}\n")
    print("wrote", path)


